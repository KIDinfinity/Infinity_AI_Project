def main():
    with open(MAP_FILE) as f:
        day_map = {int(k): v for k, v in json.load(f).items()}

    # 收集 day 目录 → (day_no, date)
    day_dirs = {}
    for phase in sorted(os.listdir(PLAN_ROOT)):
        p = os.path.join(PLAN_ROOT, phase)
        if not os.path.isdir(p) or not phase.startswith("phase_"):
            continue
        for week in sorted(os.listdir(p)):
            w = os.path.join(p, week)
            if not os.path.isdir(w) or not week.startswith("week_"):
                continue
            for day in sorted(os.listdir(w)):
                d = os.path.join(w, day)
                if os.path.isdir(d) and day.startswith("day"):
                    no = int(day.split("_")[0][3:])
                    date = day.split("_")[1] if "_" in day else ""
                    date = f"{date[:4]}-{date[4:6]}-{date[6:8]}" if len(date) == 8 else date
                    day_dirs[no] = (d, date)

    for day_no in range(1, 85):
        if day_no not in day_dirs or day_no not in day_map:
            print(f"  ⚠️ 跳过 day{day_no:02d}")
            continue
        d, date = day_dirs[day_no]
        rng = day_map[day_no]
        title = TITLES[day_no]
        content = build_plan(day_no, date, rng, title)
        with open(os.path.join(d, "PLAN.md"), "w", encoding="utf-8") as f:
            f.write(content)
        print(f"  ✅ day{day_no:02d} {date} {title}")

    print("✅ 84 个 PLAN.md 已重写为详细版")


if __name__ == "__main__":
    main()
