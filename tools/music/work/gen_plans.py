def week_of(day_no):
    return (day_no - 1) // 7 + 1


def phase_of(day_no):
    w = week_of(day_no)
    return 1 if w <= 4 else (2 if w <= 8 else 3)


def rng_text(rng):
    s, e = rng
    if s == e:
        return f"第{s}小节"
    return f"第{s}–{e}小节"


